import { createHash } from 'crypto';
import { lstatSync, mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join, relative } from 'path';
import { afterEach, describe, expect, it } from 'vitest';
import { validateProducerPackage } from '../src/transfer/package';
import { emitRepairedCandidate, scanCandidate, type TraceClass } from '../src/transfer/scrub';

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

const pin = (ch: string) => ch.repeat(40);

function patchFor(file: string, added: string[]): string {
  const lines = added.map(line => `+${line}`);
  const side = lines.length === 1 ? '+1' : `+1,${lines.length}`;
  return [
    `diff --git a/${file} b/${file}`,
    'index 1111111..2222222 100644',
    `--- a/${file}`,
    `+++ b/${file}`,
    `@@ -1 ${side} @@`,
    '-old',
    ...lines,
    '',
  ].join('\n');
}

interface Fixture {
  root: string;
  dir: string;
}

function writeFixture(opts: {
  patch?: string;
  overlay?: Record<string, unknown>;
  extra?: Record<string, string>;
} = {}): Fixture {
  const root = mkdtempSync(join(tmpdir(), 'gitkitchen-pt3-'));
  roots.push(root);
  const dir = join(root, 'package');
  mkdirSync(dir);
  const patch = opts.patch ?? patchFor('src/note.txt', ['hello']);
  const patchSha256 = createHash('sha256').update(patch).digest('hex');
  const manifest: Record<string, unknown> = {
    schemaVersion: 1,
    sourceBaseSha: pin('a'),
    sourceTipSha: pin('b'),
    patchSha256,
    linkId: 'link-opaque-1',
    stripComponents: 1,
    eol: 'lf',
    denyGlobs: [] as string[],
    mode: 'apply',
    ...opts.overlay,
  };
  writeFileSync(join(dir, 'changes.patch'), patch);
  writeFileSync(join(dir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  writeFileSync(join(dir, 'SHA256SUMS'), `${patchSha256}  changes.patch\n`);
  for (const [name, body] of Object.entries(opts.extra ?? {})) {
    const abs = join(dir, name);
    mkdirSync(join(abs, '..'), { recursive: true });
    writeFileSync(abs, body);
  }
  return { root, dir };
}

function snapshot(dir: string): string[] {
  const out: string[] = [];
  const walk = (current: string) => {
    for (const name of readdirSync(current).sort()) {
      const abs = join(current, name);
      const rel = relative(dir, abs);
      const st = lstatSync(abs);
      if (st.isSymbolicLink()) { out.push(`link ${rel}`); continue; }
      if (st.isDirectory()) { out.push(`dir ${rel}`); walk(abs); continue; }
      const hash = createHash('sha256').update(readFileSync(abs)).digest('hex');
      out.push(`file ${rel} ${hash}`);
    }
  };
  walk(dir);
  return out;
}

function expectUntouched(dir: string, run: () => void) {
  const before = snapshot(dir);
  run();
  expect(snapshot(dir)).toEqual(before);
}

function expectRefused(patch: string, result: { reason: 'scrub' | 'deny'; class?: TraceClass }, overlay?: Record<string, unknown>) {
  const fx = writeFixture({ patch, overlay });
  expectUntouched(fx.dir, () => {
    expect(scanCandidate(fx.dir)).toEqual({ outcome: 'refuse', ...result });
  });
}

describe('clean candidate', () => {
  it('passes two independent scans and does not keep state from a refuse', () => {
    const clean = writeFixture();
    const dirty = writeFixture({ patch: patchFor('src/note.txt', ['See Claude']) });
    const dirtyBefore = snapshot(dirty.dir);
    expectUntouched(clean.dir, () => {
      expect(scanCandidate(clean.dir)).toEqual({ outcome: 'PASS' });
      expect(scanCandidate(dirty.dir)).toEqual({ outcome: 'refuse', reason: 'scrub', class: 'ai-tool' });
      expect(scanCandidate(clean.dir)).toEqual({ outcome: 'PASS' });
    });
    expect(snapshot(dirty.dir)).toEqual(dirtyBefore);
  });

  it('keeps a removed trace and still passes', () => {
    const patch = [
      'diff --git a/src/note.txt b/src/note.txt',
      '--- a/src/note.txt',
      '+++ b/src/note.txt',
      '@@ -1 +1 @@',
      '-Heroeskitchen marker',
      '+hello',
      '',
    ].join('\n');
    const fx = writeFixture({ patch });
    expectUntouched(fx.dir, () => {
      expect(scanCandidate(fx.dir)).toEqual({ outcome: 'PASS' });
    });
  });
});

describe('named classes', () => {
  it('refuses Co-authored-by', () => {
    expectRefused(patchFor('src/note.txt', ['Co-authored-by: Sam <sam@example.com>']), { reason: 'scrub', class: 'co-authored-by' });
  });

  it('refuses Generated-by', () => {
    expectRefused(patchFor('src/note.txt', ['Generated-by: release']), { reason: 'scrub', class: 'generated-by' });
    expectRefused(patchFor('src/note.txt', ['generated by release']), { reason: 'scrub', class: 'generated-by' });
  });

  it('refuses an AI tool name', () => {
    expectRefused(patchFor('src/note.txt', ['See Claude']), { reason: 'scrub', class: 'ai-tool' });
    const css = writeFixture({ patch: patchFor('src/note.txt', ['cursor: pointer']) });
    expect(scanCandidate(css.dir)).toEqual({ outcome: 'PASS' });
  });

  it('refuses a session URL', () => {
    expectRefused(patchFor('src/note.txt', ['https://cursor.com/agents/abc123']), { reason: 'scrub', class: 'session-url' });
    expectRefused(patchFor('src/note.txt', ['https://chatgpt.com/c/abc123']), { reason: 'scrub', class: 'session-url' });
  });

  it('refuses Heroeskitchen org, repo, and private-path strings', () => {
    expectRefused(patchFor('src/note.txt', ['Heroeskitchen']), { reason: 'scrub', class: 'heroeskitchen' });
    expectRefused(patchFor('src/note.txt', ['Heroeskitchen/gitkitchen']), { reason: 'scrub', class: 'heroeskitchen' });
    expectRefused(patchFor('src/note.txt', ['Heroeskitchen/private-ops/transfer']), { reason: 'scrub', class: 'heroeskitchen' });
    expectRefused(patchFor('src/note.txt', ['private-ops/transfer']), { reason: 'scrub', class: 'heroeskitchen' });
  });

  it('refuses an internal doc path', () => {
    expectRefused(patchFor('docs/internal/notes.md', ['hello']), { reason: 'deny', class: 'internal-doc' });
    expectRefused(patchFor('INTERNAL.md', ['hello']), { reason: 'deny', class: 'internal-doc' });
  });

  it('refuses a context or prompt path', () => {
    expectRefused(patchFor('prompts/system.md', ['hello']), { reason: 'deny', class: 'context-prompt' });
    expectRefused(patchFor('prompt.md', ['hello']), { reason: 'deny', class: 'context-prompt' });
  });

  it('refuses an agent log region', () => {
    expectRefused(patchFor('src/note.txt', ['#region agent log']), { reason: 'scrub', class: 'agent-log' });
  });

  it('refuses a localhost ingest URL', () => {
    expectRefused(patchFor('src/note.txt', ['http://127.0.0.1:9/ingest/abc']), { reason: 'scrub', class: 'localhost-ingest' });
    expectRefused(patchFor('src/note.txt', ['http://localhost:9/ingest/abc']), { reason: 'scrub', class: 'localhost-ingest' });
  });

  it('refuses a context file stored in the candidate and does not delete it', () => {
    const fx = writeFixture({ extra: { 'prompts/system.md': 'hello' } });
    const before = snapshot(fx.dir);
    expect(scanCandidate(fx.dir)).toEqual({ outcome: 'refuse', reason: 'deny', class: 'context-prompt' });
    const dest = join(fx.root, 'repaired');
    expect(emitRepairedCandidate(fx.dir, dest).outcome).toBe('refuse');
    expect(snapshot(fx.dir)).toEqual(before);
    expect(readFileSync(join(fx.dir, 'prompts/system.md'), 'utf8')).toBe('hello');
    expect(() => lstatSync(dest)).toThrow();
  });
});

describe('path deny', () => {
  it('refuses a denyGlobs match and a .git path', () => {
    expectRefused(patchFor('secrets/token.txt', ['nope']), { reason: 'deny' }, { denyGlobs: ['secrets/**'] });
    expectRefused(patchFor('keys/a.pem', ['nope']), { reason: 'deny' }, { denyGlobs: ['*.pem'] });
    expectRefused(patchFor('.git/config', ['nope']), { reason: 'deny' });
    const allowed = writeFixture({ patch: patchFor('src/sub/note.txt', ['hello']), overlay: { denyGlobs: ['src/*.txt'] } });
    expect(scanCandidate(allowed.dir)).toEqual({ outcome: 'PASS' });
  });
});

describe('repair', () => {
  it('emits a new directory that passes validation and a second scan', () => {
    const patch = patchFor('src/note.txt', ['hello', 'Co-authored-by: Sam <sam@example.com>']);
    const fx = writeFixture({ patch, extra: { 'note.txt.orig': 'keep-me' } });
    const before = snapshot(fx.dir);
    const dest = join(fx.root, 'repaired');
    expect(emitRepairedCandidate(fx.dir, dest)).toEqual({ outcome: 'PASS' });
    expect(dest).not.toBe(fx.dir);
    expect(snapshot(fx.dir)).toEqual(before);
    expect(readFileSync(join(fx.dir, 'changes.patch'), 'utf8')).toContain('Co-authored-by: Sam <sam@example.com>');
    expect(readFileSync(join(fx.dir, 'note.txt.orig'), 'utf8')).toBe('keep-me');
    const repaired = readFileSync(join(dest, 'changes.patch'), 'utf8');
    expect(repaired).toContain('+hello');
    expect(repaired).not.toContain('Co-authored-by');
    expect(readdirSync(dest).sort()).toEqual(['SHA256SUMS', 'changes.patch', 'manifest.json']);
    expect(validateProducerPackage(dest).outcome).toBe('PASS');
    expect(scanCandidate(dest)).toEqual({ outcome: 'PASS' });
    expect(scanCandidate(dest)).toEqual({ outcome: 'PASS' });
  });

  it('drops an agent-log region and a denied file from the new package only', () => {
    const region = patchFor('src/note.txt', [
      'hello',
      '// #region agent log',
      'fetch("http://127.0.0.1:9/ingest/abc")',
      '// #endregion',
    ]);
    const fx = writeFixture({ patch: region + patchFor('prompts/system.md', ['hello']) });
    const before = snapshot(fx.dir);
    const dest = join(fx.root, 'repaired');
    expect(emitRepairedCandidate(fx.dir, dest)).toEqual({ outcome: 'PASS' });
    expect(snapshot(fx.dir)).toEqual(before);
    const repaired = readFileSync(join(dest, 'changes.patch'), 'utf8');
    expect(repaired).toContain('+hello');
    expect(repaired).not.toContain('#region agent log');
    expect(repaired).not.toContain('ingest');
    expect(repaired).not.toContain('prompts/system.md');
    expect(validateProducerPackage(dest).outcome).toBe('PASS');
    expect(scanCandidate(dest)).toEqual({ outcome: 'PASS' });
    expect(scanCandidate(dest)).toEqual({ outcome: 'PASS' });
  });

  it('does not drop lines after an unclosed agent log region', () => {
    const fx = writeFixture({ patch: patchFor('src/note.txt', ['hello', '// #region agent log', 'const kept = 1']) });
    const before = snapshot(fx.dir);
    const dest = join(fx.root, 'repaired');
    expect(scanCandidate(fx.dir)).toEqual({ outcome: 'refuse', reason: 'scrub', class: 'agent-log' });
    expect(emitRepairedCandidate(fx.dir, dest)).toEqual({ outcome: 'refuse', reason: 'scrub', class: 'agent-log' });
    expect(snapshot(fx.dir)).toEqual(before);
    expect(readFileSync(join(fx.dir, 'changes.patch'), 'utf8')).toContain('const kept = 1');
    expect(() => lstatSync(dest)).toThrow();
  });

  it('does not rewrite a line of functional code', () => {
    const fx = writeFixture({ patch: patchFor('src/note.txt', ['const name = "Claude"']) });
    const before = snapshot(fx.dir);
    const dest = join(fx.root, 'repaired');
    expect(emitRepairedCandidate(fx.dir, dest)).toEqual({ outcome: 'refuse', reason: 'scrub', class: 'ai-tool' });
    expect(snapshot(fx.dir)).toEqual(before);
    expect(() => lstatSync(dest)).toThrow();
  });

  it('does not write the repair inside the candidate', () => {
    const fx = writeFixture({ patch: patchFor('src/note.txt', ['hello', 'Co-authored-by: Sam <sam@example.com>']) });
    const before = snapshot(fx.dir);
    expect(emitRepairedCandidate(fx.dir, join(fx.dir, 'repaired')).outcome).toBe('refuse');
    expect(snapshot(fx.dir)).toEqual(before);
  });
});

describe('fail closed', () => {
  it('refuses a timeout and does not write a target', () => {
    const fx = writeFixture();
    const target = join(fx.root, 'target-repo');
    mkdirSync(target);
    writeFileSync(join(target, 'keep.txt'), 'stay');
    const before = snapshot(fx.root);
    let reads = 0;
    let ticks = 0;
    const now = () => (ticks++ === 0 ? 0 : 10_000);
    expect(scanCandidate(fx.dir, {
      now,
      deadlineMs: 1000,
      readFile: () => { reads++; return Buffer.from('x'); },
    })).toEqual({ outcome: 'refuse', reason: 'timeout' });
    expect(reads).toBe(0);
    let repairTicks = 0;
    const repairNow = () => (repairTicks++ === 0 ? 0 : 10_000);
    expect(emitRepairedCandidate(fx.dir, join(fx.root, 'repaired'), {
      now: repairNow,
      deadlineMs: 1000,
      readFile: () => { reads++; return Buffer.from('x'); },
    })).toEqual({ outcome: 'refuse', reason: 'timeout' });
    expect(reads).toBe(0);
    expect(snapshot(fx.root)).toEqual(before);
  });

  it('refuses a thrown read and does not write a target', () => {
    const fx = writeFixture();
    const target = join(fx.root, 'target-repo');
    mkdirSync(target);
    writeFileSync(join(target, 'keep.txt'), 'stay');
    const before = snapshot(fx.root);
    expect(scanCandidate(fx.dir, { readFile: () => { throw new Error('failed'); } })).toEqual({ outcome: 'refuse', reason: 'error' });
    expect(emitRepairedCandidate(fx.dir, join(fx.root, 'repaired'), {
      readFile: () => { throw new Error('failed'); },
    })).toEqual({ outcome: 'refuse', reason: 'error' });
    expect(snapshot(fx.root)).toEqual(before);
  });

  it('refuses a symlink without following it', () => {
    const fx = writeFixture();
    symlinkSync(join(fx.root, 'target-repo'), join(fx.dir, 'alias'));
    expectUntouched(fx.dir, () => {
      expect(scanCandidate(fx.dir)).toEqual({ outcome: 'refuse', reason: 'error' });
    });
  });
});

