import { existsSync, readFileSync, readdirSync, mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { describe, expect, it } from 'vitest';
import { validateProducerPackage } from '../src/transfer/package';
import { produceTransferPackage } from '../src/transfer/produce';
import { initRepo, makeWorld, put, sh } from './transfer-fixtures';
import { mkdtempSync } from 'fs';
import { tmpdir } from 'os';

describe('produceTransferPackage', () => {
  it('writes the three files under transfer/patches and passes producer validation', async () => {
    const w = await makeWorld();
    expect(w.pkgDir).toBe(join(w.hk, 'transfer', 'patches', 'link-a', '2026-11-08-sample'));
    expect(readdirSync(w.pkgDir).sort()).toEqual(['SHA256SUMS', 'changes.patch', 'manifest.json']);
    const v = validateProducerPackage(w.pkgDir);
    expect(v.outcome).toBe('PASS');
    if (v.outcome === 'PASS') { expect(v.sourceBaseSha).toBe(w.baseSha); expect(v.sourceTipSha).toBe(w.tipSha); expect(v.targetBaseSha).toBeUndefined(); }
  });
  it('refuses zero diff', async () => {
    const w = await makeWorld();
    const r = await produceTransferPackage({ sourceRepo: w.hk, base: w.tipSha, tip: w.tipSha, linkId: 'link-a', slug: 'none' });
    expect(r).toEqual({ outcome: 'refuse', reason: 'zero-diff' });
  });
  it('refuses a diff that touches a denied path', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'gk-prod-'));
    const base = initRepo(dir, { 'a.txt': 'x\n' });
    put(dir, { 'AGENTS.md': 'private\n' });
    sh(dir, 'add', '-A'); sh(dir, 'commit', '-qm', 'tip');
    const r = await produceTransferPackage({ sourceRepo: dir, base, tip: 'HEAD', linkId: 'link-a', slug: 's' });
    expect(r).toEqual({ outcome: 'refuse', reason: 'validate' });
    expect(existsSync(join(dir, 'transfer'))).toBe(false);
  });
  it('refuses a patch that carries a trace', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'gk-prod-'));
    const base = initRepo(dir, { 'a.txt': 'x\n' });
    put(dir, { 'a.txt': 'x\n// Generated by a tool\n' });
    sh(dir, 'commit', '-qam', 'tip');
    const r = await produceTransferPackage({ sourceRepo: dir, base, tip: 'HEAD', linkId: 'link-a', slug: 's' });
    expect(r.outcome).toBe('refuse');
    expect(existsSync(join(dir, 'transfer'))).toBe(false);
  });
  it('refuses a destination outside transfer/patches and leaves an existing package alone', async () => {
    const w = await makeWorld();
    const out = await produceTransferPackage({ sourceRepo: w.hk, base: w.baseSha, tip: w.tipSha, linkId: 'link-a', slug: 'x', outDir: join(w.hk, 'elsewhere') });
    expect(out).toEqual({ outcome: 'refuse', reason: 'destination' });
    const before = readFileSync(join(w.pkgDir, 'changes.patch'));
    const again = await produceTransferPackage({ sourceRepo: w.hk, base: w.baseSha, tip: w.tipSha, linkId: 'link-a', slug: 'sample', date: '2026-11-08' });
    expect(again).toEqual({ outcome: 'refuse', reason: 'exists' });
    expect(readFileSync(join(w.pkgDir, 'changes.patch')).equals(before)).toBe(true);
  });
  it('refuses binary changes', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'gk-prod-'));
    const base = initRepo(dir, { 'a.txt': 'x\n' });
    writeFileSync(join(dir, 'img.bin'), Buffer.from([0, 1, 2, 0, 255]));
    sh(dir, 'add', '-A'); sh(dir, 'commit', '-qm', 'bin');
    expect((await produceTransferPackage({ sourceRepo: dir, base, tip: 'HEAD', linkId: 'link-a', slug: 'b' }))).toEqual({ outcome: 'refuse', reason: 'binary' });
    mkdirSync(join(dir, 'x'), { recursive: true });
  });
});
