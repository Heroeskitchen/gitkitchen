// Scan an HK transfer candidate. Refuse on a deny or scrub hit.
// A repair is written only as a new directory. Candidate bytes stay as they were.
// This module does not open or write a target folder.

import { createHash } from 'crypto';
import { lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { isAbsolute, join, relative, resolve, sep } from 'path';
import { validateProducerPackage } from './package';

export type TraceClass =
  | 'co-authored-by'
  | 'generated-by'
  | 'ai-tool'
  | 'session-url'
  | 'heroeskitchen'
  | 'internal-doc'
  | 'context-prompt'
  | 'agent-log'
  | 'localhost-ingest';

export interface ScanPass {
  outcome: 'PASS';
}

export interface ScanRefuse {
  outcome: 'refuse';
  reason: 'scrub' | 'deny' | 'timeout' | 'error';
  class?: TraceClass;
}

export type ScanResult = ScanPass | ScanRefuse;

export interface ScanOptions {
  /** Injectable clock. The first call is the start time. */
  now?: () => number;
  /** Refuse when the clock moves this far from the start. Default is 5 seconds. */
  deadlineMs?: number;
  /** Injectable file read. Unexpected throws become refuse. */
  readFile?: (file: string) => Buffer;
}

const DEFAULT_DEADLINE_MS = 5000;
const PACKAGE_NAMES = new Set(['changes.patch', 'manifest.json', 'SHA256SUMS']);

const CO_AUTHORED = /co-authored-by\s*:/i;
const GENERATED_BY = /generated-by\s*:|generated by\b/i;
const AGENT_REGION = /#region agent log\b/i;
const REGION_START = /^(?:\/\/|\/\*+|\*|#)?\s*#region agent log\b/i;
const REGION_END = /^(?:\/\/|\/\*+|\*|#)?\s*#endregion\b/i;
const LOCALHOST_INGEST = /https?:\/\/(?:127\.0\.0\.1|localhost|\[::1\])(?::\d+)?\/ingest\b/i;
const SESSION_URL = /https?:\/\/(?:[\w.-]+\.)*(?:chatgpt\.com|claude\.ai|cursor\.com)\/\S+|https?:\/\/\S+\/(?:sessions?|transcripts?)\/\S+|[?&](?:session|sessionId)=/i;
const HEROESKITCHEN = /heroeskitchen/i;
const PRIVATE_OPS = /\bprivate-ops\b/i;
const WHOLE_PRIVATE = /^private-ops(?:\/[A-Za-z0-9._-]+)*$/i;
const TOOL_NAMES = /\b(?:ChatGPT|Claude|Copilot|Cursor|Codex|Gemini|Grok|Devin|Tabnine|Codeium|Windsurf|OpenAI|Anthropic)\b/;
const HUNK_HEADER = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$/;
const WHOLE_HK = /^(?:https?:\/\/github\.com\/)?heroeskitchen(?:\/[A-Za-z0-9._-]+)*$/i;
const WHOLE_TOOL = /^(?:ChatGPT|Claude|Copilot|Cursor|Codex|Gemini|Grok|Devin|Tabnine|Codeium|Windsurf|OpenAI|Anthropic)$/;

class GateTimeout extends Error {
  constructor() {
    super('timeout');
    this.name = 'GateTimeout';
  }
}

interface Gate {
  check(): void;
}

export function scanCandidate(candidateDir: string, options: ScanOptions = {}): ScanResult {
  try {
    const gate = startGate(options);
    gate.check();
    const hit = inspect(candidateDir, gate, options?.readFile);
    return hit ?? { outcome: 'PASS' };
  } catch (err) {
    if (err instanceof GateTimeout) return refuse('timeout');
    return refuse('error');
  }
}

export function emitRepairedCandidate(candidateDir: string, destDir: string, options: ScanOptions = {}): ScanResult {
  let created = false;
  try {
    const gate = startGate(options);
    gate.check();
    if (!separateDirs(candidateDir, destDir) || exists(destDir)) return refuse('error');
    const built = buildRepair(candidateDir, gate, options?.readFile);
    if (built.outcome === 'refuse') return built;
    gate.check();
    mkdirSync(destDir);
    created = true;
    writeFileSync(join(destDir, 'changes.patch'), built.patch);
    writeFileSync(join(destDir, 'manifest.json'), built.manifest);
    writeFileSync(join(destDir, 'SHA256SUMS'), built.sums);
    const validated = validateProducerPackage(destDir);
    const scanned = scanCandidate(destDir);
    if (validated.outcome !== 'PASS' || scanned.outcome !== 'PASS') {
      rmSync(destDir, { recursive: true, force: true });
      created = false;
      return scanned.outcome === 'refuse' ? scanned : refuse('scrub');
    }
    return { outcome: 'PASS' };
  } catch (err) {
    if (created) rmSync(destDir, { recursive: true, force: true });
    if (err instanceof GateTimeout) return refuse('timeout');
    return refuse('error');
  }
}

function refuse(reason: ScanRefuse['reason'], trace?: TraceClass): ScanRefuse {
  return trace === undefined ? { outcome: 'refuse', reason } : { outcome: 'refuse', reason, class: trace };
}

function startGate(options?: ScanOptions): Gate {
  const clock = options?.now ?? Date.now;
  const start = clock();
  const deadline = options?.deadlineMs ?? DEFAULT_DEADLINE_MS;
  return {
    check() {
      const elapsed = clock() - start;
      if (!Number.isFinite(deadline) || deadline < 0 || elapsed < 0 || elapsed >= deadline) throw new GateTimeout();
    },
  };
}

function inspect(candidateDir: string, gate: Gate, readFile?: ScanOptions['readFile']): ScanRefuse | undefined {
  const root = resolve(candidateDir);
  const rootStat = lstatSync(root);
  if (!rootStat.isDirectory()) return refuse('error');
  const files = listFiles(root, gate);
  const texts = new Map<string, string>();
  for (const abs of files) {
    gate.check();
    const rel = toRel(root, abs);
    const buf = load(abs, readFile);
    const text = decodeUtf8(buf);
    if (text === undefined) return refuse('error');
    texts.set(rel, text);
  }
  const globs = denyGlobs(texts.get('manifest.json'));
  for (const rel of [...texts.keys()].sort()) {
    if (PACKAGE_NAMES.has(rel)) continue;
    const pathHit = classifyPath(rel, globs);
    if (pathHit) return pathHit;
  }
  const patch = texts.get('changes.patch');
  if (patch !== undefined) {
    const parsed = parsePatch(patch);
    if (!parsed) return refuse('error');
    for (const file of parsed.files) {
      for (const rel of file.paths) {
        const pathHit = classifyPath(rel, globs);
        if (pathHit) return pathHit;
      }
      for (const hunk of file.hunks) {
        for (const line of hunk.lines) {
          if (!isAdded(line)) continue;
          const trace = classifyLine(line.slice(1));
          if (trace) return refuse('scrub', trace);
        }
      }
    }
  }
  for (const [rel, text] of [...texts.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    if (rel === 'changes.patch') continue;
    const trace = classifyText(text);
    if (trace) return refuse('scrub', trace);
  }
  return undefined;
}

interface BuiltPass {
  outcome: 'PASS';
  patch: string;
  manifest: string;
  sums: string;
}

function buildRepair(candidateDir: string, gate: Gate, readFile?: ScanOptions['readFile']): BuiltPass | ScanRefuse {
  const root = resolve(candidateDir);
  const files = listFiles(root, gate);
  const texts = new Map<string, string>();
  for (const abs of files) {
    gate.check();
    const rel = toRel(root, abs);
    const text = decodeUtf8(load(abs, readFile));
    if (text === undefined) return refuse('error');
    texts.set(rel, text);
  }
  const globs = denyGlobs(texts.get('manifest.json'));
  for (const [rel, text] of [...texts.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    if (PACKAGE_NAMES.has(rel)) continue;
    const pathHit = classifyPath(rel, globs);
    if (pathHit) return pathHit;
    const trace = classifyText(text);
    if (trace) return refuse('scrub', trace);
  }
  const patch = texts.get('changes.patch');
  const manifest = texts.get('manifest.json');
  const sums = texts.get('SHA256SUMS');
  if (patch === undefined || manifest === undefined || sums === undefined) return refuse('error');
  const manifestTrace = classifyText(manifest);
  if (manifestTrace) return refuse('scrub', manifestTrace);
  const sumsTrace = classifyText(sums);
  if (sumsTrace) return refuse('scrub', sumsTrace);

  const repaired = repairPatch(patch, globs);
  if (repaired.outcome === 'refuse') return repaired;
  if (repaired.patch === patch) return { outcome: 'PASS', patch, manifest, sums };

  const patchSha256 = sha256(repaired.patch);
  const nextManifest = replacePatchSha(manifest, patchSha256);
  if (nextManifest === undefined) return refuse('error');
  const nextSums = rewriteSums(sums, patchSha256, sha256(nextManifest));
  if (nextSums === undefined) return refuse('error');
  return { outcome: 'PASS', patch: repaired.patch, manifest: nextManifest, sums: nextSums };
}

function repairPatch(patch: string, globs: string[]): { outcome: 'PASS'; patch: string } | ScanRefuse {
  const parsed = parsePatch(patch);
  if (!parsed) return refuse('error');
  let dropped = false;
  let blocking: ScanRefuse | undefined;
  const rendered: string[][] = [];
  for (const file of parsed.files) {
    const pathHit = file.paths.map(rel => classifyPath(rel, globs)).find(hit => hit !== undefined);
    if (pathHit) {
      dropped = true;
      blocking = pathHit;
      continue;
    }
    let inRegion = false;
    const hunks: string[] = [];
    for (const hunk of file.hunks) {
      const kept: string[] = [];
      let oldLines = 0;
      let newLines = 0;
      let hunkDropped = false;
      for (const line of hunk.lines) {
        if (line.startsWith('\\')) {
          kept.push(line);
          continue;
        }
        if (isAdded(line)) {
          const body = line.slice(1);
          const trimmed = body.trim();
          if (REGION_START.test(trimmed)) {
            inRegion = true;
            dropped = true;
            hunkDropped = true;
            continue;
          }
          if (inRegion) {
            if (REGION_END.test(trimmed)) inRegion = false;
            dropped = true;
            hunkDropped = true;
            continue;
          }
          const trace = classifyLine(body);
          if (trace) {
            if (!lineDroppable(trimmed, trace)) return refuse('scrub', trace);
            dropped = true;
            hunkDropped = true;
            continue;
          }
          kept.push(line);
          newLines++;
          continue;
        }
        if (line.startsWith('-')) {
          kept.push(line);
          oldLines++;
          continue;
        }
        kept.push(line);
        oldLines++;
        newLines++;
      }
      if (oldLines === 0 && newLines === 0) {
        dropped = true;
        continue;
      }
      const header = hunkDropped ? formatHunk(hunk, oldLines, newLines) : hunk.raw;
      hunks.push(header, ...kept);
    }
    if (inRegion) return refuse('scrub', 'agent-log');
    if (hunks.length === 0) {
      dropped = true;
      continue;
    }
    rendered.push([...file.headers, ...hunks]);
  }
  if (rendered.length === 0) return blocking ?? refuse(dropped ? 'scrub' : 'error');
  if (!dropped) return { outcome: 'PASS', patch };
  if (parsed.newline === undefined) return refuse('error');
  const body = rendered.map(lines => lines.join(parsed.newline)).join(parsed.newline);
  return { outcome: 'PASS', patch: parsed.trailing ? body + parsed.newline : body };
}

interface Hunk {
  raw: string;
  oldStart: number;
  newStart: number;
  suffix: string;
  lines: string[];
}

interface FileDiff {
  headers: string[];
  hunks: Hunk[];
  paths: string[];
}

interface ParsedPatch {
  files: FileDiff[];
  newline: '\n' | '\r\n' | undefined;
  trailing: boolean;
}

function parsePatch(text: string): ParsedPatch | undefined {
  const crlf = text.includes('\r\n');
  if (crlf && text.replace(/\r\n/g, '').includes('\n')) return undefined;
  const newline = crlf ? '\r\n' as const : '\n' as const;
  const stripped = crlf ? text.replace(/\r\n/g, '\n') : text;
  const trailing = stripped.endsWith('\n');
  const rows = stripped.split('\n');
  if (trailing) rows.pop();
  const files: FileDiff[] = [];
  let current: FileDiff | undefined;
  let hunk: Hunk | undefined;
  for (const line of rows) {
    if (line.startsWith('diff --git ')) {
      current = { headers: [line], hunks: [], paths: [] };
      files.push(current);
      hunk = undefined;
      continue;
    }
    if (!current) return undefined;
    if (line.startsWith('@@')) {
      const header = parseHunkHeader(line);
      if (!header) return undefined;
      hunk = header;
      current.hunks.push(hunk);
      continue;
    }
    if (!hunk) current.headers.push(line);
    else hunk.lines.push(line);
  }
  if (files.length === 0 || files.some(file => file.hunks.length === 0)) return undefined;
  for (const file of files) {
    file.paths = extractPaths(file.headers);
    if (file.paths.length === 0) return undefined;
  }
  return { files, newline, trailing };
}

function parseHunkHeader(line: string): Hunk | undefined {
  const match = HUNK_HEADER.exec(line);
  if (!match) return undefined;
  return {
    raw: line,
    oldStart: Number(match[1]),
    newStart: Number(match[3]),
    suffix: match[5] ?? '',
    lines: [],
  };
}

function formatHunk(hunk: Hunk, oldLines: number, newLines: number): string {
  return `@@ -${hunkSide(hunk.oldStart, oldLines)} +${hunkSide(hunk.newStart, newLines)} @@${hunk.suffix}`;
}

function hunkSide(start: number, count: number): string {
  return count === 1 ? String(start) : `${start},${count}`;
}

function extractPaths(headers: string[]): string[] {
  const paths: string[] = [];
  for (const line of headers) {
    if (line.startsWith('diff --git ')) {
      const parts = splitTwoTokens(line.slice('diff --git '.length));
      if (!parts) continue;
      for (const token of parts) pushPath(paths, stripAb(unquote(token)));
    } else if (line.startsWith('rename from ')) pushPath(paths, unquote(line.slice('rename from '.length).trim()));
    else if (line.startsWith('rename to ')) pushPath(paths, unquote(line.slice('rename to '.length).trim()));
    else if (line.startsWith('--- ') || line.startsWith('+++ ')) {
      const token = unquote(line.slice(4).split('\t')[0].trim());
      if (token !== '/dev/null') pushPath(paths, stripAb(token));
    }
  }
  return paths;
}

function pushPath(paths: string[], rel: string | undefined): void {
  if (rel) paths.push(rel);
}

function stripAb(token: string | undefined): string | undefined {
  if (token === undefined || token === '/dev/null') return undefined;
  if (token.startsWith('a/') || token.startsWith('b/')) return token.slice(2);
  return token;
}

function splitTwoTokens(rest: string): [string, string] | undefined {
  const first = readToken(rest, 0);
  if (!first || first.next >= rest.length || rest[first.next] !== ' ') return undefined;
  const second = readToken(rest, first.next + 1);
  if (!second || second.next !== rest.length) return undefined;
  return [first.token, second.token];
}

function readToken(text: string, start: number): { token: string; next: number } | undefined {
  if (start >= text.length) return undefined;
  if (text[start] !== '"') {
    const space = text.indexOf(' ', start);
    const end = space === -1 ? text.length : space;
    if (end === start) return undefined;
    return { token: text.slice(start, end), next: end };
  }
  for (let i = start + 1; i < text.length; i++) {
    if (text[i] === '\\') { i++; continue; }
    if (text[i] === '"') return { token: text.slice(start, i + 1), next: i + 1 };
  }
  return undefined;
}

function unquote(token: string): string | undefined {
  if (!token.startsWith('"')) return token;
  if (!token.endsWith('"') || token.length < 2) return undefined;
  let out = '';
  for (let i = 1; i < token.length - 1; i++) {
    const ch = token[i];
    if (ch !== '\\') { out += ch; continue; }
    const esc = token[++i];
    if (esc === undefined) return undefined;
    if (esc === 'n') out += '\n';
    else if (esc === 't') out += '\t';
    else if (esc === '\\' || esc === '"') out += esc;
    else return undefined;
  }
  return out;
}

function classifyPath(rel: string, globs: string[]): ScanRefuse | undefined {
  const norm = rel.replace(/\\/g, '/');
  if (norm === '.git' || norm.startsWith('.git/') || norm.split('/').includes('.git')) return refuse('deny');
  if (!isSafeRelative(norm)) return refuse('deny');
  if (isContextPrompt(norm)) return refuse('deny', 'context-prompt');
  if (isInternalDoc(norm)) return refuse('deny', 'internal-doc');
  if (HEROESKITCHEN.test(norm) || norm.split('/').some(part => part.toLowerCase() === 'private-ops')) {
    return refuse('scrub', 'heroeskitchen');
  }
  if (globs.some(glob => globMatch(glob, norm))) return refuse('deny');
  return undefined;
}

function classifyText(text: string): TraceClass | undefined {
  for (const line of text.split(/\r?\n/)) {
    const trace = classifyLine(line);
    if (trace) return trace;
  }
  return undefined;
}

function classifyLine(body: string): TraceClass | undefined {
  const line = body.trim();
  if (CO_AUTHORED.test(line)) return 'co-authored-by';
  if (GENERATED_BY.test(line)) return 'generated-by';
  if (AGENT_REGION.test(line)) return 'agent-log';
  if (LOCALHOST_INGEST.test(line)) return 'localhost-ingest';
  if (SESSION_URL.test(line)) return 'session-url';
  if (HEROESKITCHEN.test(line) || PRIVATE_OPS.test(line)) return 'heroeskitchen';
  if (isPathShaped(line) && isContextPrompt(line)) return 'context-prompt';
  if (isPathShaped(line) && isInternalDoc(line)) return 'internal-doc';
  if (TOOL_NAMES.test(line)) return 'ai-tool';
  return undefined;
}

function lineDroppable(trimmed: string, trace: TraceClass): boolean {
  if (trace === 'co-authored-by') return /^co-authored-by\s*:/i.test(trimmed);
  if (trace === 'generated-by') return /^(?:generated-by\s*:|generated by\b)/i.test(trimmed);
  if (trace === 'agent-log') return REGION_START.test(trimmed) || REGION_END.test(trimmed);
  if (trace === 'localhost-ingest') return true;
  if (trace === 'session-url') return /^https?:\/\/\S+$/i.test(trimmed);
  if (trace === 'ai-tool') return WHOLE_TOOL.test(trimmed);
  if (trace === 'heroeskitchen') return WHOLE_HK.test(trimmed) || WHOLE_PRIVATE.test(trimmed);
  if (trace === 'context-prompt') return isPathShaped(trimmed) && isContextPrompt(trimmed);
  if (trace === 'internal-doc') return isPathShaped(trimmed) && isInternalDoc(trimmed);
  return false;
}

function isContextPrompt(rel: string): boolean {
  const base = baseName(rel);
  if (base === 'agents.md' || base === 'claude.md' || base === 'context.md' || base === 'prompt.md') return true;
  if (base.endsWith('.prompt') || base.endsWith('.prompt.md')) return true;
  return rel.split('/').some(part => {
    const name = part.toLowerCase();
    return name === 'prompt' || name === 'prompts' || name === '.cursor';
  });
}

function isInternalDoc(rel: string): boolean {
  const base = baseName(rel);
  if (base === 'internal.md' || base === 'internal.txt' || base === 'internal.rst') return true;
  if (base.endsWith('.internal.md')) return true;
  const parts = rel.split('/').map(part => part.toLowerCase());
  const docs = parts.indexOf('docs');
  return docs >= 0 && parts[docs + 1] === 'internal';
}

function baseName(rel: string): string {
  return rel.slice(rel.lastIndexOf('/') + 1).toLowerCase();
}

function isPathShaped(value: string): boolean {
  return value.length > 0 && !/[\s"'`]/.test(value);
}

function isSafeRelative(rel: string): boolean {
  if (rel === '' || rel.includes('\\') || rel.includes('\0')) return false;
  if (rel.startsWith('/') || /^[A-Za-z]:/.test(rel)) return false;
  return rel.split('/').every(part => part !== '' && part !== '.' && part !== '..');
}

function isAdded(line: string): boolean {
  return line.startsWith('+') && !line.startsWith('+++');
}

function denyGlobs(manifest: string | undefined): string[] {
  if (manifest === undefined) return [];
  try {
    const value = JSON.parse(manifest) as unknown;
    if (!value || typeof value !== 'object' || Array.isArray(value)) return [];
    const globs = (value as { denyGlobs?: unknown }).denyGlobs;
    if (!Array.isArray(globs)) return [];
    return globs.filter((glob): glob is string => typeof glob === 'string');
  } catch {
    return [];
  }
}

// Same glob rules as the package deny check.
function globMatch(glob: string, file: string): boolean {
  const re = globToRegExp(glob);
  if (re.test(file)) return true;
  if (!glob.includes('/')) return re.test(file.slice(file.lastIndexOf('/') + 1));
  return false;
}

function globToRegExp(glob: string): RegExp {
  let body = '';
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === '*') {
      if (glob[i + 1] === '*') {
        body += '.*';
        i++;
        if (glob[i + 1] === '/') i++;
      } else body += '[^/]*';
    } else if (ch === '?') body += '[^/]';
    else body += ch.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${body}$`);
}

function replacePatchSha(manifest: string, patchSha256: string): string | undefined {
  const matches = manifest.match(/"patchSha256"\s*:\s*"[0-9a-f]{64}"/g);
  if (!matches || matches.length !== 1) return undefined;
  return manifest.replace(/"patchSha256"\s*:\s*"[0-9a-f]{64}"/, match => match.replace(/[0-9a-f]{64}/, patchSha256));
}

function rewriteSums(original: string, patchSha256: string, manifestSha256: string): string | undefined {
  const newline = original.includes('\r\n') ? '\r\n' : '\n';
  const trailing = /\r?\n$/.test(original);
  const rows = original.split(/\r?\n/);
  if (trailing) rows.pop();
  let sawPatch = false;
  const out: string[] = [];
  for (const raw of rows) {
    if (raw === '') continue;
    const match = /^([0-9a-f]{64})  ([A-Za-z0-9._-]+)$/.exec(raw);
    if (!match) return undefined;
    if (match[2] === 'changes.patch') {
      out.push(`${patchSha256}  changes.patch`);
      sawPatch = true;
    } else if (match[2] === 'manifest.json') out.push(`${manifestSha256}  manifest.json`);
    else return undefined;
  }
  if (!sawPatch) return undefined;
  const body = out.join(newline);
  return trailing ? body + newline : body;
}

function listFiles(root: string, gate: Gate): string[] {
  const out: string[] = [];
  const stack = [root];
  while (stack.length > 0) {
    gate.check();
    const dir = stack.pop();
    if (dir === undefined) continue;
    const names = readdirSync(dir).sort();
    for (const name of names) {
      const abs = join(dir, name);
      const st = lstatSync(abs);
      if (st.isSymbolicLink() || (!st.isFile() && !st.isDirectory())) throw new Error('unsupported entry');
      if (st.isDirectory()) { stack.push(abs); continue; }
      out.push(abs);
    }
  }
  return out;
}

function load(file: string, readFile?: ScanOptions['readFile']): Buffer {
  return readFile ? readFile(file) : readFileSync(file);
}

function toRel(root: string, abs: string): string {
  return relative(root, abs).split(sep).join('/');
}

function separateDirs(candidateDir: string, destDir: string): boolean {
  const cand = resolve(candidateDir);
  const dest = resolve(destDir);
  return !isInside(cand, dest) && !isInside(dest, cand);
}

function isInside(parent: string, child: string): boolean {
  const rel = relative(parent, child);
  return rel === '' || (!rel.startsWith(`..${sep}`) && rel !== '..' && !isAbsolute(rel));
}

function exists(file: string): boolean {
  try {
    lstatSync(file);
    return true;
  } catch {
    return false;
  }
}

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

function decodeUtf8(buf: Buffer): string | undefined {
  try { return new TextDecoder('utf-8', { fatal: true }).decode(buf); } catch { return undefined; }
}
