// Read-only checks for a transfer package directory.
// Producer stage does not require targetBaseSha. Receiver stage does.
// Nothing in this module writes, applies a patch, or opens a target folder.

import { createHash } from 'crypto';
import { lstatSync, readFileSync, readdirSync } from 'fs';
import { join } from 'path';

export const SCHEMA_VERSION = 1;

const PACKAGE_FILES = new Set(['manifest.json', 'changes.patch', 'SHA256SUMS']);
const EOL_VALUES = new Set(['lf', 'crlf', 'auto']);
const KNOWN_FIELDS = new Set([
  'schemaVersion', 'sourceBaseSha', 'sourceTipSha', 'targetBaseSha', 'patchSha256',
  'linkId', 'stripComponents', 'eol', 'denyGlobs', 'mode', 'preimageBlobs',
]);
const CLIENT_FOLDER_FIELDS = new Set([
  'clientFolder', 'clientPath', 'clientDir', 'targetPath', 'targetDir', 'targetRepo',
  'targetFolder', 'applyPath', 'applyTarget', 'launchPath', 'launchTarget',
]);

const SCRUB = /heroeskitchen|co-authored-by\s*:|generated by\b/i;
const FULL_SHA = /^[0-9a-fA-F]{40}$|^[0-9a-fA-F]{64}$/;
const PATCH_SHA = /^[0-9a-f]{64}$/;
const LINK_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/;
const HUNK = /^@@ -\d+(?:,\d+)? \+\d+(?:,\d+)? @@/;

export type Eol = 'lf' | 'crlf' | 'auto';

export type RefuseReason =
  | 'schema'
  | 'sha256sums'
  | 'hash'
  | 'pin'
  | 'strip'
  | 'eol'
  | 'empty'
  | 'target'
  | 'deny'
  | 'scrub'
  | 'client-folder';

export interface PackagePass {
  outcome: 'PASS';
  patchSha256: string;
  sourceBaseSha: string;
  sourceTipSha: string;
  /** Present when the manifest recorded a valid pin. Not a folder. */
  targetBaseSha?: string;
  linkId: string;
}

export interface PackageRefuse {
  outcome: 'refuse';
  reason: RefuseReason;
  field?: string;
}

export type PackageValidation = PackagePass | PackageRefuse;

/**
 * Client folders are denied as launch or apply targets.
 * There is no switch that turns this on.
 */
export function clientFolderLaunchOrApply(): 'denied' {
  return 'denied';
}

export function validateProducerPackage(packageDir: string): PackageValidation {
  return validatePackage(packageDir, 'producer');
}

export function validateReceiverPackage(packageDir: string): PackageValidation {
  return validatePackage(packageDir, 'receiver');
}

function refuse(reason: RefuseReason, field?: string): PackageRefuse {
  return field === undefined ? { outcome: 'refuse', reason } : { outcome: 'refuse', reason, field };
}

function validatePackage(packageDir: string, stage: 'producer' | 'receiver'): PackageValidation {
  let names: string[];
  try {
    const dirStat = lstatSync(packageDir);
    if (!dirStat.isDirectory()) return refuse('schema', 'package');
    names = readdirSync(packageDir);
    for (const name of names) {
      const st = lstatSync(join(packageDir, name));
      if (!st.isFile()) return refuse('schema', name);
    }
  } catch {
    return refuse('schema', 'package');
  }

  if (!names.includes('SHA256SUMS')) return refuse('sha256sums', 'SHA256SUMS');
  if (!names.includes('manifest.json') || !names.includes('changes.patch')) return refuse('schema', 'package');
  if (names.some(name => !PACKAGE_FILES.has(name))) return refuse('schema', 'package');

  let manifestBuf: Buffer;
  let patchBuf: Buffer;
  let sumsBuf: Buffer;
  try {
    manifestBuf = readFileSync(join(packageDir, 'manifest.json'));
    patchBuf = readFileSync(join(packageDir, 'changes.patch'));
    sumsBuf = readFileSync(join(packageDir, 'SHA256SUMS'));
  } catch {
    return refuse('schema', 'package');
  }

  const manifestText = decodeUtf8(manifestBuf);
  const patchText = decodeUtf8(patchBuf);
  const sumsText = decodeUtf8(sumsBuf);
  if (manifestText === undefined || patchText === undefined || sumsText === undefined) return refuse('schema', 'encoding');

  const parsed = parseManifest(manifestText);
  if (parsed.outcome === 'refuse') return parsed;
  const manifest = parsed.manifest;

  if (stage === 'receiver') {
    if (manifest.targetBaseSha === undefined) return refuse('target', 'targetBaseSha');
  }

  const scrubbedField = scrubbedManifestField(manifest);
  if (scrubbedField) return refuse('scrub', scrubbedField);

  const patchSha = sha256(patchBuf);
  const sums = parseSums(sumsText);
  if (!sums) return refuse('hash', 'SHA256SUMS');
  const listedPatch = sums.get('changes.patch');
  if (listedPatch === undefined || listedPatch !== patchSha || manifest.patchSha256 !== patchSha) return refuse('hash', 'patchSha256');
  const listedManifest = sums.get('manifest.json');
  if (listedManifest !== undefined && listedManifest !== sha256(manifestBuf)) return refuse('hash', 'manifest.json');

  const patch = inspectPatch(patchText);
  if (patch.hunks === 0) return refuse('empty', 'changes.patch');
  if (patch.malformed || patch.gitHeaders === 0 || patch.paths.length === 0) return refuse('schema', 'changes.patch');

  for (const rel of patch.paths) {
    if (!isSafeRelative(rel)) return refuse('schema', 'changes.patch');
    if (rel === '.git' || rel.startsWith('.git/') || globDenied(manifest.denyGlobs, rel)) return refuse('deny', rel);
    if (SCRUB.test(rel)) return refuse('scrub', rel);
  }
  for (const line of patch.addedLines) {
    if (SCRUB.test(line)) return refuse('scrub', 'changes.patch');
  }

  if (manifest.preimageBlobs) {
    const touched = new Set(patch.paths);
    for (const rel of Object.keys(manifest.preimageBlobs)) {
      if (!touched.has(rel)) return refuse('schema', 'preimageBlobs');
    }
  }

  const pass: PackagePass = {
    outcome: 'PASS',
    patchSha256: manifest.patchSha256,
    sourceBaseSha: manifest.sourceBaseSha,
    sourceTipSha: manifest.sourceTipSha,
    linkId: manifest.linkId,
  };
  if (manifest.targetBaseSha !== undefined) pass.targetBaseSha = manifest.targetBaseSha;
  return pass;
}

interface Manifest {
  sourceBaseSha: string;
  sourceTipSha: string;
  targetBaseSha?: string;
  patchSha256: string;
  linkId: string;
  denyGlobs: string[];
  preimageBlobs?: Record<string, string>;
}

function parseManifest(text: string): { outcome: 'ok'; manifest: Manifest } | PackageRefuse {
  let value: unknown;
  try { value = JSON.parse(text); } catch { return refuse('schema', 'manifest.json'); }
  if (!value || typeof value !== 'object' || Array.isArray(value)) return refuse('schema', 'manifest.json');
  if (Object.getPrototypeOf(value) !== Object.prototype) return refuse('schema', 'manifest.json');
  const obj = value as Record<string, unknown>;

  for (const key of Object.keys(obj)) {
    if (CLIENT_FOLDER_FIELDS.has(key)) return refuse('client-folder', key);
  }
  for (const key of Object.keys(obj)) {
    if (!KNOWN_FIELDS.has(key)) return refuse('schema', key);
  }

  if (obj.schemaVersion !== SCHEMA_VERSION) return refuse('schema', 'schemaVersion');
  if (obj.mode !== 'apply') return refuse('schema', 'mode');
  if (typeof obj.linkId !== 'string' || !LINK_ID.test(obj.linkId)) return refuse('schema', 'linkId');
  if (typeof obj.stripComponents !== 'number' || !Number.isInteger(obj.stripComponents) || obj.stripComponents !== 1) {
    return refuse('strip', 'stripComponents');
  }
  if (typeof obj.eol !== 'string' || !EOL_VALUES.has(obj.eol)) return refuse('eol', 'eol');
  if (!Array.isArray(obj.denyGlobs)) return refuse('schema', 'denyGlobs');
  const denyGlobs: string[] = [];
  for (const glob of obj.denyGlobs) {
    if (!isDenyGlob(glob)) return refuse('schema', 'denyGlobs');
    denyGlobs.push(glob);
  }

  if (!isFullSha(obj.sourceBaseSha)) return refuse('pin', 'sourceBaseSha');
  if (!isFullSha(obj.sourceTipSha)) return refuse('pin', 'sourceTipSha');
  // A present target pin must already be a full sha. A folder path is not a pin.
  let targetBaseSha: string | undefined;
  if (obj.targetBaseSha !== undefined) {
    if (!isFullSha(obj.targetBaseSha)) return refuse('target', 'targetBaseSha');
    targetBaseSha = obj.targetBaseSha.toLowerCase();
  }
  if (typeof obj.patchSha256 !== 'string' || !PATCH_SHA.test(obj.patchSha256)) return refuse('hash', 'patchSha256');

  let preimageBlobs: Record<string, string> | undefined;
  if (obj.preimageBlobs !== undefined) {
    const blobs = parsePreimage(obj.preimageBlobs);
    if (!blobs) return refuse('schema', 'preimageBlobs');
    preimageBlobs = blobs;
  }

  return {
    outcome: 'ok',
    manifest: {
      sourceBaseSha: obj.sourceBaseSha.toLowerCase(),
      sourceTipSha: obj.sourceTipSha.toLowerCase(),
      ...(targetBaseSha === undefined ? {} : { targetBaseSha }),
      patchSha256: obj.patchSha256,
      linkId: obj.linkId,
      denyGlobs,
      ...(preimageBlobs ? { preimageBlobs } : {}),
    },
  };
}

function parsePreimage(value: unknown): Record<string, string> | undefined {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return undefined;
  if (Object.getPrototypeOf(value) !== Object.prototype) return undefined;
  const out: Record<string, string> = {};
  for (const [key, blob] of Object.entries(value as Record<string, unknown>)) {
    if (!isSafeRelative(key) || !isFullSha(blob)) return undefined;
    out[key] = blob.toLowerCase();
  }
  return out;
}

function scrubbedManifestField(manifest: Manifest): string | undefined {
  if (SCRUB.test(manifest.linkId)) return 'linkId';
  for (const glob of manifest.denyGlobs) {
    if (SCRUB.test(glob)) return 'denyGlobs';
  }
  if (manifest.preimageBlobs) {
    for (const rel of Object.keys(manifest.preimageBlobs)) {
      if (SCRUB.test(rel)) return 'preimageBlobs';
    }
  }
  return undefined;
}

function parseSums(text: string): Map<string, string> | undefined {
  const map = new Map<string, string>();
  const lines = text.split('\n');
  if (text.endsWith('\n')) lines.pop();
  for (let raw of lines) {
    if (raw.endsWith('\r')) raw = raw.slice(0, -1);
    if (raw === '') continue;
    const match = /^([0-9a-f]{64})  ([A-Za-z0-9._-]+)$/.exec(raw);
    if (!match || map.has(match[2])) return undefined;
    if (match[2] !== 'changes.patch' && match[2] !== 'manifest.json') return undefined;
    map.set(match[2], match[1]);
  }
  return map.size > 0 ? map : undefined;
}

interface PatchInfo {
  hunks: number;
  gitHeaders: number;
  malformed: boolean;
  paths: string[];
  addedLines: string[];
}

function inspectPatch(text: string): PatchInfo {
  const info: PatchInfo = { hunks: 0, gitHeaders: 0, malformed: false, paths: [], addedLines: [] };
  const lines = text.split('\n');
  if (text.endsWith('\n')) lines.pop();
  for (const line of lines) {
    if (line.startsWith('diff --git ')) {
      info.gitHeaders++;
      const header = parseDiffGit(line);
      if (!header) { info.malformed = true; continue; }
      info.paths.push(header.oldPath, header.newPath);
      continue;
    }
    if (line.startsWith('rename from ')) addRawPath(info, line.slice('rename from '.length));
    else if (line.startsWith('rename to ')) addRawPath(info, line.slice('rename to '.length));
    else if (line.startsWith('--- ')) addDiffPath(info, line.slice(4));
    else if (line.startsWith('+++ ')) addDiffPath(info, line.slice(4));
    else if (line.startsWith('@@')) {
      if (!HUNK.test(line)) info.malformed = true;
      else info.hunks++;
    } else if (line.startsWith('+')) info.addedLines.push(line.slice(1));
  }
  info.paths = info.paths.filter(p => p !== '/dev/null');
  return info;
}

function addRawPath(info: PatchInfo, token: string): void {
  const path = unquoteToken(pathToken(token));
  if (path === undefined) info.malformed = true;
  else info.paths.push(path);
}

function addDiffPath(info: PatchInfo, token: string): void {
  const raw = unquoteToken(pathToken(token));
  if (raw === undefined) { info.malformed = true; return; }
  if (raw === '/dev/null') return;
  if (raw.startsWith('a/') || raw.startsWith('b/')) info.paths.push(raw.slice(2));
  else info.malformed = true;
}

function parseDiffGit(line: string): { oldPath: string; newPath: string } | undefined {
  const parts = splitTwoTokens(line.slice('diff --git '.length));
  if (!parts) return undefined;
  const oldPath = prefixedPath(parts[0], 'a/');
  const newPath = prefixedPath(parts[1], 'b/');
  if (oldPath === undefined || newPath === undefined) return undefined;
  return { oldPath, newPath };
}

function prefixedPath(token: string, prefix: 'a/' | 'b/'): string | undefined {
  const raw = token.startsWith('"') ? unquote(token) : token;
  if (raw === undefined || !raw.startsWith(prefix)) return undefined;
  return raw.slice(prefix.length);
}

function splitTwoTokens(rest: string): [string, string] | undefined {
  const first = readToken(rest, 0);
  if (!first || first.next >= rest.length || rest[first.next] !== ' ') return undefined;
  const second = readToken(rest, first.next + 1);
  if (!second || second.next !== rest.length) return undefined;
  return [first.token, second.token];
}

function readToken(text: string, start: number): { token: string; next: number } | undefined {
  if (start >= text.length) return undefined;
  if (text[start] !== '"') {
    const space = text.indexOf(' ', start);
    const end = space === -1 ? text.length : space;
    if (end === start) return undefined;
    return { token: text.slice(start, end), next: end };
  }
  for (let i = start + 1; i < text.length; i++) {
    if (text[i] === '\\') { i++; continue; }
    if (text[i] === '"') return { token: text.slice(start, i + 1), next: i + 1 };
  }
  return undefined;
}

function pathToken(token: string): string {
  const tab = token.indexOf('\t');
  return (tab === -1 ? token : token.slice(0, tab)).trim();
}

function unquoteToken(token: string): string | undefined {
  return token.startsWith('"') ? unquote(token) : token;
}

function unquote(token: string): string | undefined {
  if (!token.startsWith('"') || !token.endsWith('"') || token.length < 2) return undefined;
  let out = '';
  for (let i = 1; i < token.length - 1; i++) {
    const ch = token[i];
    if (ch !== '\\') { out += ch; continue; }
    const esc = token[++i];
    if (esc === undefined) return undefined;
    if (esc === 'n') out += '\n';
    else if (esc === 't') out += '\t';
    else if (esc === '\\' || esc === '"') out += esc;
    else return undefined;
  }
  return out;
}

function isSafeRelative(rel: string): boolean {
  if (rel === '' || rel.includes('\\') || rel.includes('\0') || rel.includes('\n') || rel.includes('\r')) return false;
  if (rel.startsWith('/') || /^[A-Za-z]:/.test(rel)) return false;
  const parts = rel.split('/');
  return parts.every(part => part !== '' && part !== '.' && part !== '..');
}

function isDenyGlob(value: unknown): value is string {
  if (typeof value !== 'string' || value.length === 0 || value.length > 256) return false;
  if (value.startsWith('!') || value.startsWith('/') || value.includes('\\') || value.includes('\0')) return false;
  return !value.split('/').includes('..');
}

function globDenied(globs: string[], rel: string): boolean {
  return globs.some(glob => globMatch(glob, rel));
}

function globMatch(glob: string, file: string): boolean {
  const re = globToRegExp(glob);
  if (re.test(file)) return true;
  if (!glob.includes('/')) {
    const base = file.slice(file.lastIndexOf('/') + 1);
    return re.test(base);
  }
  return false;
}

function globToRegExp(glob: string): RegExp {
  let body = '';
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === '*') {
      if (glob[i + 1] === '*') {
        body += '.*';
        i++;
        if (glob[i + 1] === '/') i++;
      } else body += '[^/]*';
    } else if (ch === '?') body += '[^/]';
    else body += ch.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${body}$`);
}

function isFullSha(value: unknown): value is string {
  return typeof value === 'string' && FULL_SHA.test(value);
}

function sha256(buf: Buffer): string {
  return createHash('sha256').update(buf).digest('hex');
}

function decodeUtf8(buf: Buffer): string | undefined {
  try { return new TextDecoder('utf-8', { fatal: true }).decode(buf); } catch { return undefined; }
}
